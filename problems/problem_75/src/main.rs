struct Solution;

impl Solution {
    pub fn sort_colors(nums: &mut Vec<i32>) {
        let mut count = [0usize; 3];

        for &num in nums.iter() {
            count[num as usize] += 1;
        }

        let mut z = 0;

        for i in 0..3 {
            for _ in 0..count[i] {
                nums[z] = i as i32;
                z += 1;
            }
        }
    }
}

